// 反論への応酬：選択肢は毎回同じ四つ。反論リリースと三つの証拠は、どの分岐でも開ける。やり直しなし。
const REBUTTAL_DOCS = ["rebuttal", "regHistory", "adLibrary", "server"];
const EVIDENCE = ["法人登記の履歴", "広告ライブラリ", "サーバー・クラウド費用", "反論しない"];
const MISFIRE = ["その資料は、この主張について何も語っていない。的外れの反論は、相手に言い返す材料を渡すだけだ。"];

function rebuttal(id, next, def) {
  choice(id, "c3", {
    recap: def.claim,
    prompt: "この主張に、何を突き返すか。",
    docs: def.docs,
    retry: false,
    next,
    options: EVIDENCE.map((label, i) => {
      if (i === def.answer) return { label, judge: "o", delta: 1, gain: def.gain, text: def.hit };
      if (i === 3) return { label, judge: "tri", delta: 0, text: def.silent };
      return { label, judge: "x", delta: -1, text: MISFIRE };
    }),
  });
}

